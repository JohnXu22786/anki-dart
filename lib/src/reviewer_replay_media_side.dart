/// The card side selected for the host's Reviewer media replay request.
enum ReviewerReplayMediaSide { front, back }

/// Selects the source side passed to `cardMediaPlayer.replayAll()`.
///
/// The host reads Reviewer state, dispatches `PLAY_MEDIA`, and performs replay.
ReviewerReplayMediaSide reviewerReplayMediaSide({
  required bool showingAnswer,
}) => showingAnswer
    ? ReviewerReplayMediaSide.back
    : ReviewerReplayMediaSide.front;
